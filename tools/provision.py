"""Run ONCE on a trusted laptop (not the UNO Q) to create a device's secrets.

    python3 tools/provision.py

Zero-input mouse mode has no PIN: nothing to choose, nothing to type. This only creates the
device's random secret.

Writes (both gitignored, both secret):
    app/sketch/secrets.h          compiled into the STM32 firmware (K_MCU)
    tools/out/tag_key.json   the key the verifier uses to check the STM32's tags

Then flash the sketch from App Lab. Delete tools/out/ once the verifier has the key.
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "app", "python"))
import yuseal as ys  # noqa: E402

k_mcu = os.urandom(32)
_, k_tag = ys.mcu_keys(k_mcu)


def arr(b: bytes) -> str:
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}"


root = os.path.join(os.path.dirname(__file__), "..")
with open(os.path.join(root, "app", "sketch", "secrets.h"), "w") as f:
    f.write("// GENERATED by tools/provision.py. SECRET. Never commit.\n#pragma once\n#include <stdint.h>\n")
    f.write(f"static const uint8_t YS_K_MCU[32] = {arr(k_mcu)};\n")
os.makedirs(os.path.join(root, "tools", "out"), exist_ok=True)
with open(os.path.join(root, "tools", "out", "tag_key.json"), "w") as f:
    os.fchmod(f.fileno(), 0o600)
    json.dump({"k_tag": ys.b64(k_tag)}, f)
print("Wrote app/sketch/secrets.h and tools/out/tag_key.json")
print("Next: flash the sketch, then run `python3 app/python/main.py enrol <name>` on the board and click once.")
