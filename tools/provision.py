"""Run ONCE on a trusted laptop (not the UNO Q) to create a device's secrets.

    python3 tools/provision.py --pin ABCABCAB --duress-pin ABCABCAb

PINs use A, B, C for a short press and a, b, c for a press held 0.8 s or longer. Both PINs
must be the same length (8 to 12 presses) and differ in at least one press. The duress PIN
should differ from the normal one only by timing, so someone watching can't tell which was
entered.

Writes (both gitignored, both secret):
    app/sketch/secrets.h          compiled into the STM32 firmware (K_MCU and the two PIN tags)
    tools/out/guardian_tag_key.json   the key the guardian uses to check the STM32's tags

Then flash the sketch from App Lab. Delete tools/out/ once the guardian has the key.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "app", "python"))
import yuseal as ys  # noqa: E402

p = argparse.ArgumentParser()
p.add_argument("--pin", required=True)
p.add_argument("--duress-pin", required=True)
a = p.parse_args()

if len(a.pin) != len(a.duress_pin) or not 8 <= len(a.pin) <= 12:
    sys.exit("PINs must be the same length, 8 to 12 presses.")
if a.pin == a.duress_pin or set(a.pin + a.duress_pin) - set("ABCabc"):
    sys.exit("PINs must differ and use only A B C a b c.")
if a.pin.upper() == a.duress_pin.upper() and sum(x != y for x, y in zip(a.pin, a.duress_pin)) > 2:
    print("Tip: the best duress PIN differs from the normal one by one long press.")

k_mcu = os.urandom(32)
k_pin, k_tag = ys.mcu_keys(k_mcu)


def arr(b: bytes) -> str:
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}"


root = os.path.join(os.path.dirname(__file__), "..")
with open(os.path.join(root, "app", "sketch", "secrets.h"), "w") as f:
    f.write("// GENERATED by tools/provision.py. SECRET. Never commit.\n#pragma once\n#include <stdint.h>\n")
    f.write(f"static const uint8_t YS_K_MCU[32] = {arr(k_mcu)};\n")
    f.write(f"static const uint8_t YS_PIN_TAG_NORMAL[32] = {arr(ys.pin_tag(k_pin, a.pin))};\n")
    f.write(f"static const uint8_t YS_PIN_TAG_DURESS[32] = {arr(ys.pin_tag(k_pin, a.duress_pin))};\n")
    f.write(f"static const uint8_t YS_PIN_LEN = {len(a.pin)};\n")
os.makedirs(os.path.join(root, "tools", "out"), exist_ok=True)
with open(os.path.join(root, "tools", "out", "guardian_tag_key.json"), "w") as f:
    os.fchmod(f.fileno(), 0o600)
    json.dump({"k_tag": ys.b64(k_tag)}, f)
print("Wrote app/sketch/secrets.h and tools/out/guardian_tag_key.json")
print("Next: flash the sketch, then run `python3 app/python/main.py enrol <name>` on the board.")
